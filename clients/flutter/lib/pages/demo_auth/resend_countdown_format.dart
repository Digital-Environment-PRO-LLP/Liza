/// Остаток отсчёта повторной отправки кода как «м:сс»: `1985` → «33:05»,
/// `59` → «0:59» (LABA-2526 — «1985 с» человек в голове не переводит).
///
/// Часовой ветки нет намеренно: оба серверных потолка (на адресат и на IP)
/// — ровно час, поэтому максимум здесь «60:00». Минуты без ведущего нуля:
/// «00:59» на экране входа читается как «ноль минут».
String formatResendCountdown(int seconds) {
  final total = seconds < 0 ? 0 : seconds;
  final minutes = total ~/ 60;
  final rest = total % 60;
  return '$minutes:${rest.toString().padLeft(2, '0')}';
}
