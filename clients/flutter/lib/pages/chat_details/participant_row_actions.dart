/// Спек 2026-07-30 §1.2: истории открываются ТОЛЬКО тапом по аватарке,
/// вся остальная строка `ParticipantListItem` — контекстное меню (выдать
/// права/забанить/…). Раньше при активном кольце историй тап по ЛЮБОЙ точке
/// строки уводил в просмотрщик историй, и меню участника с активной историей
/// было недостижимо.
///
/// Выбор колбэка для `ListTile.onTap` вынесен в чистую функцию (а не оставлен
/// литеральным `hasActiveRing ? stories : menu` внутри build), чтобы регресс
/// «кто-то вернул условный переключатель обратно в onTap» ловился юнит-тестом
/// без монтирования виджета — `ParticipantListItem` требует настоящий `User`
/// из matrix-dart-sdk (Room/Client), собрать который в тесте нечем (см.
/// `test/pages/chat_details/channel_comments_test.dart`).
library;

/// Колбэк, который должен сработать по тапу на СТРОКЕ участника (не на
/// аватарке). Строка всегда открывает контекстное меню — `hasActiveRing`
/// принимается намеренно, чтобы сигнатура была симметрична состоянию,
/// которым управляется `Avatar.onStoryTap`, но на выбор не влияет: истории
/// со строки недостижимы независимо от активности кольца.
T participantRowTapCallback<T>({
  required bool hasActiveRing,
  required T openContextMenu,
  required T openStories,
}) => openContextMenu;
