import 'dart:async';

/// Координирует отправку квитанций прочтения (read receipts), не теряя САМОЕ
/// СВЕЖЕЕ намерение, пока предыдущий PUT `/read_markers` ещё в полёте.
///
/// Зачем (баг «аватарка прочтения появляется только после ответа»): раньше
/// отправка стояла за guard'ом `if (_setReadMarkerFuture != null) return;` —
/// пока один запрос в полёте, ВСЕ последующие вызовы `setReadMarker` (в т.ч. на
/// только что прочитанное чужое сообщение) молча отбрасывались, а повторной
/// попытки до следующего события в комнате не было. В активном групповом чате
/// постоянно идут `updateView` (новые сообщения, typing, presence), поэтому
/// квитанция на чужое сообщение часто терялась и не уходила собеседнику до тех
/// пор, пока пользователь сам не отправит сообщение (его событие → новый
/// `updateView` → guard уже свободен). Собеседник не видел аватарку «прочитал»
/// до ответа.
///
/// Координатор запоминает ПОСЛЕДНИЙ запрос и повторяет его сразу по завершении
/// текущего — позиция прочтения гарантированно догоняет живой конец таймлайна,
/// при этом одновременно в полёте не более одного запроса (без шторма PUT).
class ReadMarkerSendCoordinator {
  Future<void>? _inFlight;
  Future<void>? Function()? _pending;

  bool get isInFlight => _inFlight != null;

  /// Запросить отправку. [send] выполняет фактическую отправку и возвращает её
  /// future, либо `null`, если отправка не нужна/заблокирована гейтами (тогда
  /// ничего не «в полёте» и накопленный pending не теряется — догонит позже).
  ///
  /// future из [send] НЕ должен завершаться ошибкой (на стороне вызывающего
  /// цепочка глушит ошибку через `catchError`); координатор лишь дожидается
  /// завершения через `whenComplete`.
  void request(Future<void>? Function() send) {
    if (_inFlight != null) {
      // Важна только САМАЯ СВЕЖАЯ позиция прочтения — перезаписываем pending.
      _pending = send;
      return;
    }
    _start(send);
  }

  void _start(Future<void>? Function() send) {
    _pending = null;
    final future = send();
    // Гейты заблокировали отправку (null) — ничего не в полёте, ждать нечего.
    if (future == null) return;
    _inFlight = future.whenComplete(() {
      _inFlight = null;
      final pending = _pending;
      _pending = null;
      if (pending != null) _start(pending);
    });
  }
}
